    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a pay period first.", "No selection", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        javax.swing.table.TableModel model = jTable1.getModel();
        // ID is column 0 (hidden), start column 1, end column 2
        selectedPeriodId = String.valueOf(model.getValueAt(row, 0));
        selectedPeriodStart = String.valueOf(model.getValueAt(row, 1));
        selectedPeriodEnd = String.valueOf(model.getValueAt(row, 2));

        // close dialog and return selection to caller
        this.dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

