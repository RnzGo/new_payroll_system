    private void initPeriodTable() {
        // Replace the table model with a dynamic one and load data from DAO
        DefaultTableModel model = new DefaultTableModel(new Object[]{"ID", "Period Start", "Period End"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };

        try {
            PayrollPeriodDAO dao = new PayrollPeriodDAO();
            List<String[]> periods = dao.getAllPayrollPeriods();
            for (String[] p : periods) {
                // p[0]=id, p[1]=start, p[2]=end, p[3]=date_issued
                model.addRow(new Object[]{p[0], p[1], p[2]});
            }
        } catch (Exception ex) {
            System.err.println("Error loading payroll periods: " + ex.getMessage());
        }

        jTable1.setModel(model);
        // hide the ID column visually but keep it in the model
        if (jTable1.getColumnModel().getColumnCount() > 0) {
            javax.swing.table.TableColumn idCol = jTable1.getColumnModel().getColumn(0);
            idCol.setMinWidth(0);
            idCol.setMaxWidth(0);
            idCol.setPreferredWidth(0);
        }

        jTable1.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        // double-click to select
        jTable1.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                if (evt.getClickCount() == 2) {
                    jButton1ActionPerformed(null);
                }
            }
        });
    }

